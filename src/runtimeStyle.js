// Numeric preferences that apply to actors owned by the dock or the shell
// (padding, spacing, radii) cannot go through inline styles, which those
// components overwrite. They are written to a small generated stylesheet
// instead, loaded on top of stylesheet.css.

import Gio from 'gi://Gio';
import GLib from 'gi://GLib';
import St from 'gi://St';

const DOCK = '#dashtodockContainer.glass-shell-dock';

export function buildRuntimeCss(look) {
    const along = Math.max(Math.ceil(look.iconSpacing / 2), look.magnifyGrowth);
    const across = Math.max(4, look.magnifyGrowth);
    return `/* Generated by Glass Shell. Do not edit. */
${DOCK} #dash { padding: ${look.dockPadding}px; }
${DOCK}.bottom #dashtodockBox { padding-bottom: ${look.dockMargin}px; }
${DOCK}.top #dashtodockBox { padding-top: ${look.dockMargin}px; }
${DOCK}.left #dashtodockBox { padding-left: ${look.dockMargin}px; }
${DOCK}.right #dashtodockBox { padding-right: ${look.dockMargin}px; }
${DOCK}.bottom .dash-item-container > .app-well-app,
${DOCK}.bottom .dash-item-container > .show-apps,
${DOCK}.top .dash-item-container > .app-well-app,
${DOCK}.top .dash-item-container > .show-apps { padding: ${across}px ${along}px; }
${DOCK}.left .dash-item-container > .app-well-app,
${DOCK}.left .dash-item-container > .show-apps,
${DOCK}.right .dash-item-container > .app-well-app,
${DOCK}.right .dash-item-container > .show-apps { padding: ${along}px ${across}px; }
${DOCK} .app-well-app .overview-icon,
${DOCK} .show-apps .overview-icon { border-radius: ${Math.max(6, look.radius - look.dockPadding)}px; }
.popup-menu-content.glass-shell-menu,
.notification-banner.glass-shell-banner { border-radius: ${look.radius}px; }
`;
}

export class RuntimeStyleSheet {
    constructor(name) {
        this._dir = GLib.build_filenamev([GLib.get_user_runtime_dir(), name]);
        this._file = null;
        this._css = null;
        this._generation = 0;
    }

    update(css) {
        if (css === this._css)
            return;
        GLib.mkdir_with_parents(this._dir, 0o700);
        // Alternate between two files so the sheet being unloaded is never
        // the file that was just rewritten.
        const file = Gio.File.new_for_path(
            GLib.build_filenamev([this._dir, `runtime-${this._generation++ % 2}.css`]));
        file.replace_contents(new TextEncoder().encode(css), null, false,
            Gio.FileCreateFlags.REPLACE_DESTINATION, null);

        const theme = St.ThemeContext.get_for_stage(global.stage).get_theme();
        if (this._file)
            theme.unload_stylesheet(this._file);
        theme.load_stylesheet(file);
        this._file = file;
        this._css = css;
    }

    destroy() {
        if (this._file)
            St.ThemeContext.get_for_stage(global.stage).get_theme().unload_stylesheet(this._file);
        this._file = null;
        this._css = null;
        for (const index of [0, 1]) {
            try {
                Gio.File.new_for_path(GLib.build_filenamev([this._dir, `runtime-${index}.css`])).delete(null);
            } catch {
                // Already gone.
            }
        }
    }
}
